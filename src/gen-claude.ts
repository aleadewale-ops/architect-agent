// Generates the Claude Code files for subscription mode from the same source of
// truth the router uses (models, prompts, knowledge sources):
//   .claude/agents/architect-*.md   subagents, one per (model, effort)
//   .claude/settings.json           web access to the curated sources, run-dir writes
// Run `npm run gen:claude` after changing prompts, sources or agent table.
// A test fails if the committed files are out of date.

import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { z } from "zod";
import { PLANNER_AGENT, REVIEWER_AGENTS, WORKER_AGENTS, type AgentDef } from "./agents.js";
import { SOURCES } from "./knowledge.js";
import { MODELS } from "./models.js";
import { PlanSchema } from "./plan-schema.js";
import { PLANNER_SYSTEM, VERIFIER_SYSTEM, WORKER_SYSTEM } from "./prompts.js";

const GENERATED = "<!-- Generated by src/gen-claude.ts - edit the source, then run `npm run gen:claude`. -->";

function frontmatter(a: AgentDef, description: string, tools: string[]): string {
  const lines = ["---", `name: ${a.name}`, `description: ${description}`, `model: ${a.model}`];
  if (a.effort && MODELS[a.model].effort) lines.push(`effort: ${a.effort}`);
  lines.push(`tools: ${tools.join(", ")}`, "---");
  return lines.join("\n");
}

const curatedHosts = [...new Set(SOURCES.flatMap((s) => s.hosts))].sort();

const RESEARCH_NOTES = `## Research
WebSearch cannot be restricted by domain, so restrict it yourself: search the curated sources first with \`site:\` queries (e.g. \`site:arxiv.org Littlewood-Richardson\`, \`site:mathoverflow.net ...\`) and fetch pages with WebFetch. Curated hosts: ${curatedHosts.join(", ")}. Use other sites only when the curated ones have nothing, and say so.`;

function plannerBody(): string {
  const schema = JSON.stringify(z.toJSONSchema(PlanSchema));
  return `${PLANNER_SYSTEM}

# How you work here (Claude Code subscription mode)
The orchestrator gives you a run directory. Read \`<run>/task.md\` (and the attached file it names, if any, and \`<run>/backlog.md\` if it exists).
Write the plan as JSON to \`<run>/plan.json\`, valid against this JSON Schema:

\`\`\`json
${schema}
\`\`\`

If the orchestrator sends you validation errors, rewrite \`<run>/plan.json\` to fix all of them.
Reply with at most 5 lines: the strategy in one sentence and the node count. The file is the handoff; do not paste the JSON in your reply.`;
}

function workerBody(): string {
  return `${WORKER_SYSTEM}

# How you work here (Claude Code subscription mode)
The orchestrator's message gives you: the mission, your node (id, role, goal, acceptance criteria), input files (outputs of dependencies and of your subagents, with any reviewer issues), and your output path.
1. Read every input file you are given. Do not read other nodes' files and do not spawn agents.
2. Do the work. For small computations or checks of small cases, run \`python3\` via Bash.
3. Write your complete result as markdown to your output path. Start with a one-line summary.
4. Reply with at most 3 lines: \`DONE\`, \`DONE WITH UNCERTAINTY\` or \`BLOCKED: <why>\`, plus one sentence. Do not repeat the result - the file is the handoff, which keeps the orchestrator's context small.

${RESEARCH_NOTES}`;
}

function reviewerBody(): string {
  return `${VERIFIER_SYSTEM}

# How you work here (Claude Code subscription mode)
The orchestrator gives you: the node's goal and acceptance criteria, the output file to review, the attempt number, and the review path.
- Read the output file. Spot-check the riskiest claims: open cited arXiv/abstract pages with WebFetch when a citation looks doubtful; re-run small computations with \`python3\` when cheap.
- Write the review to the review path in exactly this format:

\`\`\`
VERDICT: PASS or FAIL
ATTEMPT: <attempt number>
- <issue 1>
- <issue 2>
\`\`\`

- Reply with the VERDICT line and the number of issues only.`;
}

export function renderClaudeFiles(): Record<string, string> {
  const files: Record<string, string> = {};
  const add = (a: AgentDef, description: string, tools: string[], body: string) => {
    files[`.claude/agents/${a.name}.md`] = `${frontmatter(a, description, tools)}\n${GENERATED}\n\n${body}\n`;
  };

  add(PLANNER_AGENT, "Architect planner: turns a task into an agent/subagent/sub-subagent plan (plan.json). Used by the /architect skill.", ["Read", "Glob", "Grep", "Write"], plannerBody());
  for (const a of WORKER_AGENTS) {
    const m = MODELS[a.model];
    add(a, `Architect worker (${a.model}${a.effort ? `, ${a.effort} effort` : ""}): ${m.strengths}. Runs one plan node for the /architect skill.`, ["Read", "Write", "Glob", "Grep", "Bash", "WebSearch", "WebFetch"], workerBody());
  }
  for (const a of REVIEWER_AGENTS) {
    add(a, `Architect reviewer (${a.model}, ${a.effort} effort): checks one node's output against its acceptance criteria for the /architect skill.`, ["Read", "Write", "Bash", "WebFetch"], reviewerBody());
  }

  const settings = {
    permissions: {
      allow: [
        "Bash(npx tsx src/run-tools.ts:*)",
        "Bash(npm run -s architect -- tasks:*)",
        "Bash(npm run -s architect -- skills:*)",
        "Edit(/.architect/**)",
        "WebSearch",
        ...curatedHosts.flatMap((h) => [`WebFetch(domain:${h})`, `WebFetch(domain:*.${h})`]),
      ],
    },
  };
  files[".claude/settings.json"] = `${JSON.stringify(settings, null, 2)}\n`;
  return files;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === resolve(process.argv[1])) {
  for (const [path, content] of Object.entries(renderClaudeFiles())) {
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, content);
    console.log(`wrote ${path}`);
  }
}
